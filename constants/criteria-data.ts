export function getComplianceLevel(percentage: number): {
  label: string;
  color: string;
  bgColor: string;
} {
  if (percentage >= 80) {
    return { label: "ممتاز", color: "#16A34A", bgColor: "#DCFCE7" };
  } else if (percentage >= 60) {
    return { label: "جيد", color: "#D97706", bgColor: "#FEF3C7" };
  } else {
    return { label: "يحتاج تحسين", color: "#DC2626", bgColor: "#FEE2E2" };
  }
}
